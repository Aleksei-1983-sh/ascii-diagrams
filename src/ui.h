/*
 ui.h
 Интерфейс для отрисовки всего приложения: draw_all и вспомогательные функции.
 
 Файл содержит объявления функций для отрисовки UI элементов:
 - кнопок управления
 - блоков (прямоугольников) диаграммы
 - соединений между блоками
 - панели редактирования
 
 Структуры:
 - UiDrawContext_t - контекст для передачи параметров отрисовки
*/
#ifndef ASCIIFLOW_UI_H
#define ASCIIFLOW_UI_H

#include "config.h"
#include "diagram.h"
#include "panel.h"
#include "debug.h"

/**
 * @brief Контекст отрисовки UI
 * 
 * Структура для группировки параметров, передаваемых в функции отрисовки.
 * Это уменьшает количество отдельных параметров и упрощает код.
 */
typedef struct
{
    int editing;        /**< Флаг режима редактирования (1 - активно, 0 - неактивно) */
    int edit_idx;       /**< Индекс редактируемого блока в массиве rects */
    int conn_move_active; /**< Флаг перемещения соединения (зарезервировано) */
    int conn_selected;  /**< Индекс выбранного соединения (зарезервировано) */
    int last_mouse_x;   /**< Последняя позиция мыши по X (зарезервировано) */
    int last_mouse_y;   /**< Последняя позиция мыши по Y (зарезервировано) */
} UiDrawContext_t;

/**
 * @brief Отрисовка всех элементов интерфейса
 * 
 * Функция очищает экран и отрисовывает все элементы диаграммы:
 * кнопки управления, соединения, блоки, панель редактирования (если активна)
 * и статусную строку с информацией о состоянии приложения.
 * 
 * @param ctx Контекст отрисовки, содержащий все необходимые флаги и параметры
 */
void ui_draw_all(const UiDrawContext_t *ctx);

/**
 * @brief Отрисовка декоративной рамки (бокса)
 * 
 * Рисует прямоугольную рамку с заданными координатами и размерами.
 * Используется для создания визуальных границ в интерфейсе.
 * 
 * @param x Координата X левого верхнего угла рамки (в экранных координатах)
 * @param y Координата Y левого верхнего угла рамки (в экранных координатах)
 * @param box_w Ширина рамки в символах
 * @param box_h Высота рамки в символах
 * @param title Заголовок рамки (отображается в верхней границе), может быть NULL
 */
void ui_draw_box(int x, int y, int box_w, int box_h, const char *title);

#endif
